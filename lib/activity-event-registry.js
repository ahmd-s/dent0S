export function getEventLabel(event) {
  return EVENT_LABELS[event] || event?.replace(/_/g, ' ').toLowerCase().replace(/^\w/, c => c.toUpperCase()) || 'Activity'
}

export function getModuleForEvent(event) {
  return EVENT_MODULE_MAP[event] || ACTIVITY_MODULES.PLATFORM
}
